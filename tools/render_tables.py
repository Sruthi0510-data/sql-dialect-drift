"""Write the README's data tables from the experiment JSON, between committed markers.

Hand-typed table cells are the largest hole in a receipts mechanism. An anchor
phrase guards a figure quoted in a sentence; a table of thirty numbers is thirty
figures nobody anchored, and the first one to go stale goes stale silently.

So the tables are generated, CI regenerates them and fails if the committed
README differs, and the same values are published in docs/metrics.json under
`table_values` so the backward check in check_numbers.py recognises them.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
EXPERIMENTS = ROOT / "docs" / "experiments"


def _block(name: str, body: str, source: str) -> str:
    return (
        f"<!-- table:{name} generated by tools/render_tables.py from {source} -->\n"
        f"{body}\n"
        f"<!-- /table:{name} -->"
    )


def _payload() -> dict[str, Any]:
    return json.loads((EXPERIMENTS / "exp01.json").read_text())


def queries_table() -> tuple[str, list[Any]]:
    """Every query, how many ways it splits the warehouses, and why."""
    import sys

    sys.path.insert(0, str(ROOT / "src"))
    from sdd.differential import run_suite
    from sdd.queries import SUITE

    report = run_suite(SUITE)
    values: list[Any] = []
    lines = [
        "| query | parses everywhere | answers | explained by |",
        "| --- | --- | --- | --- |",
    ]
    for result in report.results:
        axes = result.explained_by or result.jointly_explained_by
        label = "agrees everywhere" if not result.diverges else ", ".join(axes)
        values.append(len(result.groups))
        lines.append(
            f"| `{result.query}` | yes | {len(result.groups)} | {label} |"
        )
    return _block("queries", "\n".join(lines), "the suite"), values


def pairs_table() -> tuple[str, list[Any]]:
    """Every pair of warehouses and how many queries they disagree on."""
    payload = _payload()
    values: list[Any] = []
    lines = ["| from | to | queries that disagree |", "| --- | --- | --- |"]
    for row in payload["pairs"]:
        values.append(row["diverging"])
        lines.append(f"| {row['left']} | {row['right']} | {row['diverging']} |")
    return _block("pairs", "\n".join(lines), "exp01.json"), values


def blind_table() -> tuple[str, list[Any]]:
    """What the model fails to explain when one decision is removed from it."""
    payload = _payload()
    values: list[Any] = []
    lines = [
        "| decision removed from the model | queries it can no longer explain |",
        "| --- | --- |",
    ]
    for axis, count in payload["queries_unattributed_when_blinded"].items():
        values.append(count)
        lines.append(f"| `{axis}` | {count} |")
    return _block("blind", "\n".join(lines), "exp01.json"), values


def table_values() -> list[Any]:
    values: list[Any] = []
    for builder in (queries_table, pairs_table, blind_table):
        _, produced = builder()
        values.extend(produced)
    return values


def main() -> int:
    text = README.read_text(encoding="utf-8")
    replaced = 0
    for name, builder in (("queries", queries_table), ("pairs", pairs_table), ("blind", blind_table)):
        block, _ = builder()
        pattern = re.compile(rf"<!-- table:{name}.*?-->.*?<!-- /table:{name} -->", re.DOTALL)
        if not pattern.search(text):
            print(f"no marker block for {name!r} in README.md")
            return 1
        text = pattern.sub(lambda _match, block=block: block, text)
        replaced += 1
    README.write_text(text, encoding="utf-8")
    print(f"rewrote {replaced} generated table block(s) in README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
